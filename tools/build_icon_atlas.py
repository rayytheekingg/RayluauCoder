#!/usr/bin/env python3
"""Pack SVG or PNG icons into Roblox sprite sheets and generate IconAtlas.luau.

Usage:
    python3 tools/build_icon_atlas.py <icons_dir> <out_dir> [--size 128] [--padding 12]
                                      [--sheet 1024] [--keep-colors]

- SVGs are recolored white (currentColor and black fills become #FFFFFF) so Roblox can tint them
  with ImageColor3. Use --keep-colors for multi-color art (for example Kenney icons).
- PNGs are scaled to fit the cell and kept as-is.
- Writes atlas_0.png, atlas_1.png, ... (each at most --sheet pixels square) and IconAtlas.luau.
- After uploading each sheet, replace the ATLAS_n placeholders in IconAtlas.luau with the asset IDs.

Needs Pillow, plus rsvg-convert (librsvg) or the cairosvg package for SVG input.
"""
import argparse
import io
import re
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

WHITE_PATTERNS = [
    (re.compile(r"currentColor", re.IGNORECASE), "#FFFFFF"),
    (re.compile(r'(fill|stroke)="(#000|#000000|black)"', re.IGNORECASE), r'\1="#FFFFFF"'),
]


def render_svg(svg_text: str, pixels: int) -> Image.Image:
    data = svg_text.encode("utf-8")
    if shutil.which("rsvg-convert"):
        result = subprocess.run(
            ["rsvg-convert", "-w", str(pixels), "-h", str(pixels), "--keep-aspect-ratio"],
            input=data,
            capture_output=True,
            check=True,
        )
        return Image.open(io.BytesIO(result.stdout)).convert("RGBA")
    try:
        import cairosvg  # type: ignore
    except ImportError:
        sys.exit("Need rsvg-convert or the cairosvg package to render SVGs.")
    png = cairosvg.svg2png(bytestring=data, output_width=pixels, output_height=pixels)
    return Image.open(io.BytesIO(png)).convert("RGBA")


def load_icon(path: Path, inner: int, keep_colors: bool) -> Image.Image:
    if path.suffix.lower() == ".svg":
        text = path.read_text(encoding="utf-8")
        if not keep_colors:
            for pattern, replacement in WHITE_PATTERNS:
                text = pattern.sub(replacement, text)
        return render_svg(text, inner)
    image = Image.open(path).convert("RGBA")
    image.thumbnail((inner, inner), Image.LANCZOS)
    return image


def icon_name(path: Path) -> str:
    return re.sub(r"[^a-z0-9_]+", "_", path.stem.lower()).strip("_")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("icons_dir", type=Path)
    parser.add_argument("out_dir", type=Path)
    parser.add_argument("--size", type=int, default=128, help="cell size in px")
    parser.add_argument("--padding", type=int, default=12, help="padding inside each cell in px")
    parser.add_argument("--sheet", type=int, default=1024, help="max sheet width and height in px")
    parser.add_argument("--keep-colors", action="store_true", help="do not recolor SVGs to white")
    args = parser.parse_args()

    sources = sorted(p for p in args.icons_dir.iterdir() if p.suffix.lower() in {".svg", ".png"})
    if not sources:
        sys.exit(f"No .svg or .png files in {args.icons_dir}")

    per_row = args.sheet // args.size
    per_sheet = per_row * per_row
    inner = args.size - 2 * args.padding
    args.out_dir.mkdir(parents=True, exist_ok=True)

    entries = []
    seen = set()
    sheets = []
    for index, path in enumerate(sources):
        name = icon_name(path)
        if name in seen:
            sys.exit(f"Duplicate icon name after cleanup: {name} ({path.name})")
        seen.add(name)

        sheet_index, slot = divmod(index, per_sheet)
        if sheet_index == len(sheets):
            remaining = min(per_sheet, len(sources) - index)
            rows = -(-remaining // per_row)
            cols = per_row if remaining >= per_row else remaining
            sheets.append(Image.new("RGBA", (cols * args.size, rows * args.size), (0, 0, 0, 0)))
        row, col = divmod(slot, per_row)
        icon = load_icon(path, inner, args.keep_colors)
        x = col * args.size + (args.size - icon.width) // 2
        y = row * args.size + (args.size - icon.height) // 2
        sheets[sheet_index].alpha_composite(icon, (x, y))
        entries.append((name, sheet_index, col * args.size, row * args.size))

    for i, sheet in enumerate(sheets):
        sheet.save(args.out_dir / f"atlas_{i}.png")

    lines = [
        "--!strict",
        "-- IconAtlas: generated by tools/build_icon_atlas.py. Do not edit entries by hand; re-run the tool.",
        "-- Replace each ATLAS_n placeholder with the uploaded sheet's asset ID.",
        "",
        "export type Icon = {",
        "\timage: string,",
        "\toffset: Vector2,",
        "\tsize: Vector2,",
        "}",
        "",
    ]
    for i in range(len(sheets)):
        lines.append(f'local ATLAS_{i} = "rbxassetid://0" -- atlas_{i}.png')
    lines += ["", "local ICONS: { [string]: Icon } = {"]
    for name, sheet_index, ox, oy in entries:
        lines.append(
            f'\t["{name}"] = {{ image = ATLAS_{sheet_index}, offset = Vector2.new({ox}, {oy}), '
            f"size = Vector2.new({args.size}, {args.size}) }},"
        )
    lines += [
        "}",
        "",
        "local IconAtlas = {}",
        "",
        "--[=[",
        "\tReturns the atlas entry for `name`, or nil if it is not in the atlas.",
        "]=]",
        "function IconAtlas.get(name: string): Icon?",
        "\treturn ICONS[name]",
        "end",
        "",
        "--[=[",
        "\tPoints `target` at the icon `name`. Returns false (and leaves target unchanged) if the icon is missing.",
        "]=]",
        "function IconAtlas.apply(target: ImageLabel | ImageButton, name: string): boolean",
        "\tlocal icon = ICONS[name]",
        "\tif not icon then",
        "\t\twarn(`[IconAtlas] unknown icon {name}`)",
        "\t\treturn false",
        "\tend",
        "\t-- Separate branches keep both solvers happy; ImageLabel and ImageButton share these properties.",
        "\t-- selene: allow(if_same_then_else)",
        "\tif target:IsA(\"ImageButton\") then",
        "\t\ttarget.Image = icon.image",
        "\t\ttarget.ImageRectOffset = icon.offset",
        "\t\ttarget.ImageRectSize = icon.size",
        "\t\ttarget.ScaleType = Enum.ScaleType.Fit",
        "\telseif target:IsA(\"ImageLabel\") then",
        "\t\ttarget.Image = icon.image",
        "\t\ttarget.ImageRectOffset = icon.offset",
        "\t\ttarget.ImageRectSize = icon.size",
        "\t\ttarget.ScaleType = Enum.ScaleType.Fit",
        "\tend",
        "\treturn true",
        "end",
        "",
        "return IconAtlas",
        "",
    ]
    (args.out_dir / "IconAtlas.luau").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(entries)} icons -> {len(sheets)} sheet(s) in {args.out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
